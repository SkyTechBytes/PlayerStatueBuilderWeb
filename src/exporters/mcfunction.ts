import type { SchematicDocument } from '../domain/schematic'

export function createMcfunction(schematic: SchematicDocument): string {
  const commands = schematic.blocks.map((block) => {
    const state = schematic.palette[block.palette]?.state
    if (!state) throw new Error(`Block references missing palette index ${block.palette}`)
    return `setblock ~${block.x} ~${block.y} ~${block.z} ${state}`
  })

  return ['# Generated by Player Statue Builder Web', ...commands, ''].join('\n')
}
